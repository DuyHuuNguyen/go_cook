CREATE INDEX IF NOT EXISTS idx_chef_schedules_overlap
    ON chef_schedules (chef_id, start_at, end_at)
    WHERE is_active = TRUE AND status IN ('HELD', 'CONFIRMED');


CREATE TABLE IF NOT EXISTS chef_service_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chef_profile_id BIGINT NOT NULL REFERENCES chef_profiles(id) ON DELETE CASCADE,
    province_code VARCHAR(20),
    ward_code VARCHAR(20),
    "is_active"       boolean            NOT NULL DEFAULT true,
    "version"         bigint             NOT NULL DEFAULT 0,
    "created_at"      bigint             NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::bigint,
    "updated_at"      bigint             NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::bigint
);


CREATE TABLE IF NOT EXISTS chef_dishes (
    chef_profile_id BIGINT NOT NULL REFERENCES chef_profiles(id) ON DELETE CASCADE,
    dish_id BIGINT NOT NULL REFERENCES dishes(id) ON DELETE CASCADE,
    PRIMARY KEY (chef_profile_id, dish_id)
);